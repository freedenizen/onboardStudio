#!/usr/bin/env python3
"""Writes Tests/Fixtures/coaching-laps.csv: four laps of a synthetic stadium circuit in RaceRender
CSV, driven fast, slow, fast, fast, so the Coaching window has corners, a best lap and something
to say. The geometry and the driving are the ones in Tests/TelemetryKitTests/CoachingFixture.swift
(straights 400 m, bends of radius 60 m, 40 m/s on the straights, constant-deceleration stops to a
minimum near each apex), so the numbers the window shows are the ones the unit tests assert.
Deterministic: run it again and the file does not change."""
import math
import os

STRAIGHT, RADIUS = 400.0, 60.0
BEND = math.pi * RADIUS
LAP = 2 * STRAIGHT + 2 * BEND
ORIGIN_LAT, ORIGIN_LON = 37.5, -122.0
M_PER_DEG_LAT = 110_540.0
M_PER_DEG_LON = 111_320.0 * math.cos(math.radians(ORIGIN_LAT))
STEP_SECONDS = 0.2

FAST = dict(top=40.0, minimum=15.0, offset=0.0, decel=4.0, accel=2.0)
SLOW = dict(top=40.0, minimum=13.0, offset=20.0, decel=3.0, accel=2.0)
DRIVINGS = [FAST, SLOW, FAST, FAST]


def point(s):
    s %= LAP
    half = STRAIGHT / 2
    if s < half:
        return s, 0.0
    if s < half + BEND:
        phi = (s - half) / RADIUS
        return half + RADIUS * math.sin(phi), -RADIUS + RADIUS * math.cos(phi)
    if s < 1.5 * STRAIGHT + BEND:
        return half - (s - half - BEND), -2 * RADIUS
    if s < 1.5 * STRAIGHT + 2 * BEND:
        psi = (s - 1.5 * STRAIGHT - BEND) / RADIUS
        return half - STRAIGHT - RADIUS * math.sin(psi), -RADIUS - RADIUS * math.cos(psi)
    return half - STRAIGHT + (s - 1.5 * STRAIGHT - 2 * BEND), 0.0


def speed(into, d):
    apexes = [half + BEND / 2 for half in (STRAIGHT / 2, 1.5 * STRAIGHT + BEND)]
    v = d["top"]
    for lap_offset in (-LAP, 0.0, LAP):
        for apex in apexes:
            slowest = apex + d["offset"] + lap_offset
            if into < slowest:
                curve = math.sqrt(d["minimum"] ** 2 + 2 * d["decel"] * (slowest - into))
            else:
                curve = math.sqrt(d["minimum"] ** 2 + 2 * d["accel"] * (into - slowest))
            v = min(v, curve)
    return v


def main():
    rows = []
    lap_starts = []
    t = 0.0
    travelled = 0.0
    lap = 0
    while lap < len(DRIVINGS):
        into = travelled - lap * LAP
        if not rows or into >= 0 and (len(lap_starts) <= lap):
            lap_starts.append(t)
        d = DRIVINGS[lap]
        v = speed(into, d)
        ahead = speed(min(into + 1, LAP), d)
        brake = 100 if ahead < v - 1e-9 else 0
        throttle = 0 if brake else 100
        x, y = point(into)
        rows.append((t, ORIGIN_LAT + y / M_PER_DEG_LAT, ORIGIN_LON + x / M_PER_DEG_LON, v, lap, throttle, brake))
        t += STEP_SECONDS
        travelled += v * STEP_SECONDS
        if travelled >= (lap + 1) * LAP:
            lap += 1
    # One last row on the line, so the fourth lap is complete.
    x, y = point(0)
    rows.append((t, ORIGIN_LAT + y / M_PER_DEG_LAT, ORIGIN_LON + x / M_PER_DEG_LON, speed(0, FAST), lap, 100, 0))
    lap_starts.append(t)

    def clock(seconds):
        h = int(seconds // 3600)
        m = int(seconds % 3600 // 60)
        s = seconds % 60
        return f"{h:02d}:{m:02d}:{s:05.2f}"

    out = os.path.join(os.path.dirname(__file__), "..", "Tests", "Fixtures", "coaching-laps.csv")
    with open(out, "w") as f:
        f.write("# RaceRender Data\n")
        f.write("# Generated by Scripts/make-coaching-fixture.py: four laps of a synthetic stadium circuit,\n")
        f.write("# driven fast, slow, fast, fast. Do not edit by hand.\n")
        for n, start in enumerate(lap_starts[1:], start=1):
            f.write(f"# Lap {n}: {clock(start)}\n")
        f.write("Time,Latitude,Longitude,MPH,Lap,Throttle,Brake\n")
        for t, lat, lon, v, lap, throttle, brake in rows:
            f.write(f"{clock(t)},{lat:.6f},{lon:.6f},{v * 2.2369363:.2f},{lap},{throttle},{brake}\n")
    print(f"wrote {out}: {len(rows)} rows, laps at {[round(s, 1) for s in lap_starts]}")


if __name__ == "__main__":
    main()
